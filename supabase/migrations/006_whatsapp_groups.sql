-- ---------------------------------------------------------------------------
-- whatsapp_group
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS whatsapp_group (
  id_whatsapp_group INTEGER PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  id_users INTEGER NOT NULL REFERENCES users (id_users) ON DELETE CASCADE,
  whatsapp_group_id VARCHAR(255) NOT NULL,
  title VARCHAR(100) NOT NULL,
  invite_code VARCHAR(64) NOT NULL,
  id_group_category INTEGER NOT NULL REFERENCES group_category (id_group_category),
  max_capacity INTEGER NOT NULL DEFAULT 1024,
  current_members INTEGER NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT whatsapp_group_capacity_chk CHECK (max_capacity BETWEEN 200 AND 1024),
  CONSTRAINT whatsapp_group_members_nonneg_chk CHECK (current_members >= 0),
  CONSTRAINT whatsapp_group_user_jid_uniq UNIQUE (id_users, whatsapp_group_id)
);

CREATE INDEX IF NOT EXISTS whatsapp_group_user_idx
  ON whatsapp_group (id_users);

CREATE INDEX IF NOT EXISTS whatsapp_group_user_active_idx
  ON whatsapp_group (id_users, is_active);

CREATE INDEX IF NOT EXISTS whatsapp_group_category_idx
  ON whatsapp_group (id_group_category);

CREATE OR REPLACE FUNCTION set_whatsapp_group_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS whatsapp_group_set_updated_at ON whatsapp_group;
CREATE TRIGGER whatsapp_group_set_updated_at
BEFORE UPDATE ON whatsapp_group
FOR EACH ROW
EXECUTE FUNCTION set_whatsapp_group_updated_at();

