-- Publicação no feed do Instagram e comment-to-DM (QUERO).
-- Idempotente: pode ser executado mais de uma vez no SQL Editor do Supabase.
--
-- instagram_account: hoje 1 conta default (credenciais no .env).
-- No futuro, uma linha por utilizador (id_users preenchido).

-- ---------------------------------------------------------------------------
-- product.instagram_sent
-- ---------------------------------------------------------------------------
ALTER TABLE product
  ADD COLUMN IF NOT EXISTS instagram_sent TIMESTAMPTZ;

-- ---------------------------------------------------------------------------
-- instagram_account
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS instagram_account (
  id_instagram_account INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  id_users INTEGER REFERENCES users (id_users) ON DELETE CASCADE,
  ig_business_account_id VARCHAR(64) NOT NULL,
  facebook_page_id VARCHAR(64),
  token_source VARCHAR(20) NOT NULL DEFAULT 'env',
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS instagram_account_user_uidx
  ON instagram_account (id_users)
  WHERE id_users IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS instagram_account_default_uidx
  ON instagram_account (is_default)
  WHERE is_default = TRUE;

-- ---------------------------------------------------------------------------
-- instagram_post
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS instagram_post (
  id_instagram_post INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  id_instagram_account INTEGER NOT NULL REFERENCES instagram_account (id_instagram_account) ON DELETE CASCADE,
  id_product INTEGER NOT NULL REFERENCES product (id_product) ON DELETE CASCADE,
  id_users INTEGER NOT NULL REFERENCES users (id_users) ON DELETE CASCADE,
  ig_container_id VARCHAR(64),
  ig_media_id VARCHAR(64) NOT NULL,
  caption TEXT,
  permalink TEXT,
  published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT instagram_post_media_uidx UNIQUE (ig_media_id)
);

CREATE INDEX IF NOT EXISTS instagram_post_product_idx
  ON instagram_post (id_product, published_at DESC);

CREATE INDEX IF NOT EXISTS instagram_post_users_idx
  ON instagram_post (id_users, published_at DESC);

-- ---------------------------------------------------------------------------
-- instagram_comment_dm
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS instagram_comment_dm (
  id_instagram_comment_dm INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  id_instagram_post INTEGER NOT NULL REFERENCES instagram_post (id_instagram_post) ON DELETE CASCADE,
  ig_comment_id VARCHAR(64) NOT NULL,
  ig_commenter_id VARCHAR(64) NOT NULL,
  comment_text TEXT,
  matched BOOLEAN NOT NULL DEFAULT FALSE,
  dm_status VARCHAR(20) NOT NULL DEFAULT 'skipped',
  dm_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  processed_at TIMESTAMPTZ,
  CONSTRAINT instagram_comment_dm_comment_uidx UNIQUE (ig_comment_id)
);

CREATE INDEX IF NOT EXISTS instagram_comment_dm_post_idx
  ON instagram_comment_dm (id_instagram_post, created_at DESC);

-- 1 Direct por comentador por post (claim pending+sent evita corrida)
CREATE UNIQUE INDEX IF NOT EXISTS instagram_comment_dm_claim_uidx
  ON instagram_comment_dm (id_instagram_post, ig_commenter_id)
  WHERE dm_status IN ('pending', 'sent');

-- ---------------------------------------------------------------------------
-- RLS: Next.js usa service_role (bypass). Anon não lê nem escreve.
-- ---------------------------------------------------------------------------
ALTER TABLE instagram_account ENABLE ROW LEVEL SECURITY;
ALTER TABLE instagram_post ENABLE ROW LEVEL SECURITY;
ALTER TABLE instagram_comment_dm ENABLE ROW LEVEL SECURITY;
